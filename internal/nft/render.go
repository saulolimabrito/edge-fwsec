// Package nft renders a validated policy.Config into an nftables script
// and loads it. The script only declares the project's own tables and
// replaces them atomically; other tables are never touched.
//
// Verified on nftables 1.1.5 (Rocky Linux 10.3): a file loaded with
// `nft -f` is one transaction; the "declare, delete, redefine" idiom works
// whether or not the table exists; a failing batch leaves the previous
// table intact; `iif` needs the device to exist at load time, so rules use
// `iifname`/`oifname`.
package nft

import (
	"fmt"
	"net/netip"
	"slices"
	"strings"

	"github.com/saulolimabrito/edge-fwsec/internal/policy"
)

// Owned tables. Changing these names requires a migration that deletes the
// old tables.
const (
	FilterTable = "efw_filter" // family inet
	NATTable    = "efw_nat"    // family ip
)

// Render returns the full nftables script for c. c must already pass
// policy.Validate; Render re-validates to keep the guarantee local.
func Render(c *policy.Config) (string, error) {
	if err := policy.Validate(c); err != nil {
		return "", err
	}
	r := &renderer{c: c, dev: map[string]string{}}
	for _, it := range c.Interfaces {
		r.dev[it.Name] = it.Device
	}
	return r.render()
}

type renderer struct {
	c   *policy.Config
	dev map[string]string
	b   strings.Builder
}

func (r *renderer) w(indent int, format string, a ...any) {
	r.b.WriteString(strings.Repeat("\t", indent))
	fmt.Fprintf(&r.b, format, a...)
	r.b.WriteByte('\n')
}

func (r *renderer) render() (string, error) {
	r.w(0, "#!/usr/sbin/nft -f")
	r.w(0, "# Generated by Edge FWSec. Do not edit: changes are replaced on the next apply.")
	r.w(0, "# Atomic replacement of the project's tables only.")
	r.w(0, "table inet %s", FilterTable)
	r.w(0, "delete table inet %s", FilterTable)
	r.w(0, "table ip %s", NATTable)
	r.w(0, "delete table ip %s", NATTable)
	r.w(0, "")
	if err := r.filter(); err != nil {
		return "", err
	}
	r.w(0, "")
	if err := r.nat(); err != nil {
		return "", err
	}
	return r.b.String(), nil
}

func (r *renderer) filter() error {
	f := r.c.Firewall
	r.w(0, "table inet %s {", FilterTable)

	// input
	r.w(1, "chain input {")
	r.w(2, "type filter hook input priority filter; policy drop;")
	r.w(2, "ct state vmap { established : accept, related : accept, invalid : drop }")
	r.w(2, `iifname "lo" accept`)
	r.essentialICMPv6(2, true)
	r.dhcpClients(2)
	if err := r.admin(2); err != nil {
		return err
	}
	for _, rule := range f.Rules {
		if rule.Direction == "input" && !rule.Disabled {
			if err := r.rule(2, rule); err != nil {
				return err
			}
		}
	}
	r.defaultAction(2, "input", f.DefaultInput, f.LogDefault)
	r.w(1, "}")
	r.w(0, "")

	// forward
	fwdPolicy := "drop"
	if f.DefaultForward == "accept" {
		fwdPolicy = "accept"
	}
	r.w(1, "chain forward {")
	r.w(2, "type filter hook forward priority filter; policy %s;", fwdPolicy)
	r.w(2, "ct state vmap { established : accept, related : accept, invalid : drop }")
	r.essentialICMPv6(2, false)
	// Port forwards are explicit publications: their implied accept rules
	// are evaluated before user forward rules and shown with them in the UI.
	for _, pf := range r.c.NAT.PortForwards {
		if !pf.Disabled {
			if err := r.portForwardAccept(2, pf); err != nil {
				return err
			}
		}
	}
	for _, rule := range f.Rules {
		if rule.Direction == "forward" && !rule.Disabled {
			if err := r.rule(2, rule); err != nil {
				return err
			}
		}
	}
	if fwdPolicy != "accept" {
		r.defaultAction(2, "forward", f.DefaultForward, f.LogDefault)
	}
	r.w(1, "}")
	r.w(0, "}")
	return nil
}

// essentialICMPv6 follows RFC 4890: neighbour discovery only on-link
// (hop limit 255), MLD only from link-local sources, and error messages
// (including Packet Too Big, required for PMTU discovery) always.
// Redirects are not accepted by a router.
func (r *renderer) essentialICMPv6(ind int, local bool) {
	r.w(ind, `icmpv6 type { destination-unreachable, packet-too-big, time-exceeded, parameter-problem } accept comment "efw:icmpv6-errors"`)
	if local {
		r.w(ind, `icmpv6 type { nd-router-solicit, nd-router-advert, nd-neighbor-solicit, nd-neighbor-advert } ip6 hoplimit 255 accept comment "efw:icmpv6-nd"`)
		r.w(ind, `icmpv6 type { mld-listener-query, mld-listener-report, mld-listener-done, mld2-listener-report } ip6 saddr fe80::/10 accept comment "efw:icmpv6-mld"`)
	}
}

// dhcpClients opens the replies a DHCP/DHCPv6 client needs on interfaces
// configured for it; conntrack does not associate broadcast/multicast
// requests with unicast replies.
func (r *renderer) dhcpClients(ind int) {
	var v4, v6 []string
	for _, it := range r.c.Interfaces {
		if it.IPv4.Mode == "dhcp" {
			v4 = append(v4, it.Device)
		}
		if it.IPv6.Mode == "dhcp6" || it.IPv6.Mode == "slaac" {
			v6 = append(v6, it.Device)
		}
	}
	if len(v4) > 0 {
		r.w(ind, `iifname %s udp sport 67 udp dport 68 accept comment "efw:dhcp-client"`, nameSet(v4))
	}
	if len(v6) > 0 {
		r.w(ind, `iifname %s ip6 saddr fe80::/10 udp sport 547 udp dport 546 accept comment "efw:dhcp6-client"`, nameSet(v6))
	}
}

func (r *renderer) admin(ind int) error {
	a := r.c.Admin
	var devs []string
	for _, n := range a.Interfaces {
		devs = append(devs, r.dev[n])
	}
	base := fmt.Sprintf("iifname %s", nameSet(devs))
	if len(a.Sources) == 0 {
		r.w(ind, `%s tcp dport %d accept comment "efw:admin"`, base, a.Port)
		return nil
	}
	pfx, err := policy.Resolve(r.c, a.Sources)
	if err != nil {
		return err
	}
	for _, fam := range []string{"ipv4", "ipv6"} {
		if s := prefixSet(pfx, fam); s != "" {
			r.w(ind, `%s %s saddr %s tcp dport %d accept comment "efw:admin"`, base, famKw(fam), s, a.Port)
		}
	}
	return nil
}

func (r *renderer) defaultAction(ind int, chain, action string, log bool) {
	if log {
		// Rate-limited so a scan from the WAN cannot flood the journal.
		r.w(ind, `limit rate 10/second burst 20 packets log prefix "efw default %s " comment "efw:default-log"`, chain)
	}
	if action == "reject" {
		r.w(ind, `reject with icmpx admin-prohibited comment "efw:default-reject"`)
	}
}

func (r *renderer) rule(ind int, rule policy.Rule) error {
	fams, err := policy.Families(r.c, rule)
	if err != nil {
		return err
	}
	src, err := policy.Resolve(r.c, rule.Source)
	if err != nil {
		return err
	}
	dst, err := policy.Resolve(r.c, rule.Destination)
	if err != nil {
		return err
	}
	var ifm []string
	if rule.In != "" {
		ifm = append(ifm, fmt.Sprintf(`iifname "%s"`, r.dev[rule.In]))
	}
	if rule.Out != "" {
		ifm = append(ifm, fmt.Sprintf(`oifname "%s"`, r.dev[rule.Out]))
	}
	entries := []policy.ServiceEntry{{}} // "any"
	if rule.Service != "" {
		for _, s := range r.c.Services {
			if s.Name == rule.Service {
				entries = s.Entries
			}
		}
	}
	tail := "counter"
	if rule.Log {
		tail += fmt.Sprintf(` log prefix "efw %s "`, rule.ID)
	}
	tail += " " + verdict(rule.Action)
	tail += fmt.Sprintf(` comment "efw:rule:%s"`, rule.ID)

	// Without address matches, one line covers both families.
	addrless := len(rule.Source) == 0 && len(rule.Destination) == 0
	famLines := fams
	if addrless && len(fams) == 2 {
		famLines = []string{""}
	}
	for _, fam := range famLines {
		var m []string
		m = append(m, ifm...)
		if fam != "" {
			if addrless {
				m = append(m, "meta nfproto "+fam)
			}
			if len(rule.Source) > 0 {
				m = append(m, fmt.Sprintf("%s saddr %s", famKw(fam), prefixSet(src, fam)))
			}
			if len(rule.Destination) > 0 {
				m = append(m, fmt.Sprintf("%s daddr %s", famKw(fam), prefixSet(dst, fam)))
			}
		}
		for _, e := range entries {
			sm, ok := serviceMatch(e, fam)
			if !ok {
				continue
			}
			line := slices.Clone(m)
			if sm != "" {
				line = append(line, sm)
			}
			line = append(line, tail)
			r.w(ind, "%s", strings.Join(line, " "))
		}
	}
	return nil
}

// serviceMatch renders one service entry for a family ("" = both).
// ok is false when the entry cannot match that family (icmp on IPv6).
func serviceMatch(e policy.ServiceEntry, fam string) (string, bool) {
	switch e.Protocol {
	case "":
		return "", true
	case "icmp":
		if fam == "ipv6" {
			return "", false
		}
		return "meta l4proto icmp", true
	case "icmpv6":
		if fam == "ipv4" {
			return "", false
		}
		return "meta l4proto ipv6-icmp", true
	default: // tcp, udp
		if len(e.Ports) == 0 {
			return "meta l4proto " + e.Protocol, true
		}
		return fmt.Sprintf("%s dport %s", e.Protocol, portSet(e.Ports)), true
	}
}

func verdict(a string) string {
	if a == "reject" {
		return "reject with icmpx admin-prohibited"
	}
	return a
}

func (r *renderer) portForwardAccept(ind int, pf policy.PortForward) error {
	m := []string{fmt.Sprintf(`iifname "%s"`, r.dev[pf.In])}
	if len(pf.AllowFrom) > 0 {
		p, err := policy.Resolve(r.c, pf.AllowFrom)
		if err != nil {
			return err
		}
		m = append(m, "ip saddr "+prefixSet(p, "ipv4"))
	}
	ports := pf.ExternalPorts
	if pf.TargetPort != 0 {
		ports = policy.PortRange{From: pf.TargetPort, To: pf.TargetPort}
	}
	m = append(m, "ip daddr "+pf.Target.String(), fmt.Sprintf("%s dport %s", pf.Protocol, portSet([]policy.PortRange{ports})), "ct status dnat", "counter")
	if pf.Log {
		m = append(m, fmt.Sprintf(`log prefix "efw %s "`, pf.ID))
	}
	m = append(m, fmt.Sprintf(`accept comment "efw:pf:%s"`, pf.ID))
	r.w(ind, "%s", strings.Join(m, " "))
	return nil
}

func (r *renderer) nat() error {
	r.w(0, "table ip %s {", NATTable)
	r.w(1, "chain prerouting {")
	r.w(2, "type nat hook prerouting priority dstnat; policy accept;")
	for _, pf := range r.c.NAT.PortForwards {
		if pf.Disabled {
			continue
		}
		m := []string{fmt.Sprintf(`iifname "%s"`, r.dev[pf.In])}
		if pf.ExternalAddress.IsValid() {
			m = append(m, "ip daddr "+pf.ExternalAddress.String())
		}
		if len(pf.AllowFrom) > 0 {
			p, err := policy.Resolve(r.c, pf.AllowFrom)
			if err != nil {
				return err
			}
			m = append(m, "ip saddr "+prefixSet(p, "ipv4"))
		}
		m = append(m, fmt.Sprintf("%s dport %s", pf.Protocol, portSet([]policy.PortRange{pf.ExternalPorts})), "counter")
		to := pf.Target.String()
		if pf.TargetPort != 0 {
			to = fmt.Sprintf("%s:%d", to, pf.TargetPort)
		}
		m = append(m, fmt.Sprintf(`dnat to %s comment "efw:pf:%s"`, to, pf.ID))
		r.w(2, "%s", strings.Join(m, " "))
	}
	r.w(1, "}")
	r.w(0, "")
	r.w(1, "chain postrouting {")
	r.w(2, "type nat hook postrouting priority srcnat; policy accept;")
	for _, s := range r.c.NAT.Source {
		if s.Disabled {
			continue
		}
		m := []string{fmt.Sprintf(`oifname "%s"`, r.dev[s.Out])}
		if len(s.Source) > 0 {
			p, err := policy.Resolve(r.c, s.Source)
			if err != nil {
				return err
			}
			m = append(m, "ip saddr "+prefixSet(p, "ipv4"))
		}
		m = append(m, "counter")
		if s.Mode == "snat" {
			m = append(m, "snat to "+s.ToAddress.String())
		} else {
			m = append(m, "masquerade")
		}
		m = append(m, fmt.Sprintf(`comment "efw:snat:%s"`, s.ID))
		r.w(2, "%s", strings.Join(m, " "))
	}
	r.w(1, "}")
	r.w(0, "}")
	return nil
}

func famKw(fam string) string {
	if fam == "ipv4" {
		return "ip"
	}
	return "ip6"
}

// prefixSet renders the prefixes of one family, dropping prefixes covered
// by others (nftables rejects overlapping intervals in a set).
func prefixSet(in []netip.Prefix, fam string) string {
	var ps []netip.Prefix
	for _, p := range in {
		if p.Addr().Is4() == (fam == "ipv4") {
			ps = append(ps, p.Masked())
		}
	}
	slices.SortFunc(ps, func(a, b netip.Prefix) int {
		if a.Bits() != b.Bits() {
			return a.Bits() - b.Bits()
		}
		return a.Addr().Compare(b.Addr())
	})
	var keep []netip.Prefix
	for _, p := range ps {
		covered := false
		for _, k := range keep {
			if k.Contains(p.Addr()) {
				covered = true
				break
			}
		}
		if !covered {
			keep = append(keep, p)
		}
	}
	slices.SortFunc(keep, func(a, b netip.Prefix) int { return a.Addr().Compare(b.Addr()) })
	if len(keep) == 0 {
		return ""
	}
	strs := make([]string, len(keep))
	for i, p := range keep {
		if p.IsSingleIP() {
			strs[i] = p.Addr().String()
		} else {
			strs[i] = p.String()
		}
	}
	if len(strs) == 1 {
		return strs[0]
	}
	return "{ " + strings.Join(strs, ", ") + " }"
}

// portSet merges overlapping/adjacent ranges and renders them.
func portSet(in []policy.PortRange) string {
	rs := slices.Clone(in)
	slices.SortFunc(rs, func(a, b policy.PortRange) int { return a.From - b.From })
	var merged []policy.PortRange
	for _, r := range rs {
		if n := len(merged); n > 0 && r.From <= merged[n-1].To+1 {
			merged[n-1].To = max(merged[n-1].To, r.To)
			continue
		}
		merged = append(merged, r)
	}
	strs := make([]string, len(merged))
	for i, r := range merged {
		if r.From == r.To {
			strs[i] = fmt.Sprint(r.From)
		} else {
			strs[i] = fmt.Sprintf("%d-%d", r.From, r.To)
		}
	}
	if len(strs) == 1 {
		return strs[0]
	}
	return "{ " + strings.Join(strs, ", ") + " }"
}

func nameSet(names []string) string {
	q := make([]string, len(names))
	for i, n := range names {
		q[i] = `"` + n + `"`
	}
	if len(q) == 1 {
		return q[0]
	}
	return "{ " + strings.Join(q, ", ") + " }"
}
